def legs_shift(g):
    """the other walk pose when none is drawn: the feet row shuffles one pixel"""
    last = g[-1]
    moved = '.' + last[:-1] if last[-1] == '.' else last[1:] + '.'
    return g[:-1] + [moved]


def deaths(g):
    """three death frames: it slumps, it crumples, it's a puddle in its own main colour"""
    from collections import Counter
    cnt = Counter(ch for r in g for ch in r if ch != '.')
    main = cnt.most_common(1)[0][0]
    second = cnt.most_common(2)[-1][0]
    slump = ['.' * 8] + g[:-1]
    keep = [r for i, r in enumerate(g) if i % 2 == 1]
    crumple = ['.' * 8] * (8 - len(keep)) + keep
    puddle = ['.' * 8] * 6 + ['..' + second * 3 + main + '..', '.' + main * 6 + '.']
    return [slump, crumple, puddle]


def frames(e):
    A = e['A']
    A2 = e.get('A2') or legs_shift(A)
    B = e.get('B') or A
    for g in (A, A2, B):
        assert len(g) == 8 and all(len(r) == 8 for r in g), g
    return [A, A2, A, A2, A, B] + deaths(A)   # walk A/B/A/B, tell, attack, death x3 (the enemy sheet's 9 columns)
