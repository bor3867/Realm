// Writes docs/item_rework_checklist.md: every item id, its category and rarity, whether the blueprint covers it, and its
// rework status (kept in the STATUS table below as items are finished, so none is skipped or done twice).
//   node tools/rework_checklist.mjs [path to the blueprint]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
globalThis.localStorage = { getItem: () => null, setItem: () => {} };
const { ITEMS } = await import('../src/data/items.js');
const bp = process.argv[2] || 'Z:/Downloads/realm_505_item_rework_blueprint.md';
const inBp = new Set(existsSync(bp) ? [...readFileSync(bp, 'utf8').matchAll(/^### .* — `([^`]+)`/gm)].map((m) => m[1]) : []);
const STATUS = {};                                       // id: 'done' | 'kept' (deliberately unchanged) | note
const { WEAPON_REWORK } = await import('../src/data/weapon_rework.js');
for (const [id, R] of Object.entries(WEAPON_REWORK)) STATUS[id] = `done: ${R.mech.kind}${R.mech.charge ? ' + charge' : ''}`;
for (const it of Object.values(ITEMS)) if (it.slot === 'weapon' && it.type === 'sword' && typeof it.tier === 'number') STATUS[it.id] = 'kept (tiered: plain by design)';
const rank = (it) => (it.admin ? 'admin' : it.legendary ? 'Legendary' : it.mythic ? 'Mythic' : it.ut ? 'UT' : typeof it.tier === 'number' ? 'T' + it.tier : '-');
const ORDER = ['weapon', 'ability', 'armor', 'ring', 'consumable'];
let md = '# Item rework checklist\n\nGenerated by `node tools/rework_checklist.mjs`. One row per item id; status is updated as each is finished.\n\n';
const all = Object.values(ITEMS);
md += `${all.length} items; in the blueprint: ${all.filter((it) => inBp.has(it.id)).length}; done: ${all.filter((it) => STATUS[it.id]).length}\n\n`;
for (const slot of ORDER) {
  const L = all.filter((it) => it.slot === slot);
  md += `## ${slot} (${L.length})\n\n| id | type | rarity | blueprint | status |\n|---|---|---|---|---|\n`;
  for (const it of L) md += `| \`${it.id}\` | ${it.type} | ${rank(it)} | ${inBp.has(it.id) ? 'yes' : '**missing**'} | ${STATUS[it.id] || 'todo'} |\n`;
  md += '\n';
}
writeFileSync(new URL('../docs/item_rework_checklist.md', import.meta.url), md);
console.log(`${all.length} items, ${all.filter((it) => inBp.has(it.id)).length} in the blueprint; missing from it: ${all.filter((it) => !inBp.has(it.id)).map((it) => it.id).join(', ') || 'none'}`);
