# Realmforge import, dungeons: build src/rf/explore_gen.js from the user's Realmforge explore engine (explore.js) and its
# dungeon modules (xmods/*.js). Their code runs as written (layouts, creatures, traps, rooms, every module's hooks); this
# script only cuts the seams where Realmforge stood in for a game of its own: its player, its auto-fire, its potions and
# coins, its chests' loot, its window and HUD. Those calls go to HOST (src/rf/host.js), which is our game.
# Every patch must match exactly once: if Realmforge changes under one, the build stops and says which.
#   py -I tools/rf_build_explore.py
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
src = os.path.join(root, 'realmforge-project', 'realmforge')
s = open(os.path.join(src, 'explore.js'), encoding='utf8').read()
X = os.path.join(src, 'xmods')
mods = ['00_lib.js', '01_default.js'] + sorted(f for f in os.listdir(X) if f.endswith('.js') and f not in ('00_lib.js', '01_default.js'))
mods_src = '\n'.join(open(os.path.join(X, f), encoding='utf8').read() for f in mods)

def patch(a, b, count=1):
    global s
    n = s.count(a)
    if n != count: sys.exit(f'rf_build_explore: expected {count} of {a[:90]!r}, found {n}')
    s = s.replace(a, b)

# the module: DATA and HOST come in, the engine's handles go out
patch("(function(){\n  if(!DATA.explore||!DATA.dungeons)return;", "export function makeExplore(DATA,HOST){\n  if(!DATA.explore||!DATA.dungeons)return null;")
patch('/*MODS*/', mods_src)
patch('/*PANEL*/', '')
patch("  window.RFExplore={", "  return {setup,tick,generate,damageEnemy,kill,openGate,setTile,tileAt,roomOf,solidMove,solidShot,C,BM,WALLISH,BS,TS,MODS,BOSSES,toBoss:()=>HOST.bossDoor(),")
patch("draw:()=>draw()};\n})();", "draw:()=>draw()};\n}")
# no temporary player sprite (the test piece is not in the data)
patch("E.player=arts(X.player,true);", "E.player=null;")
# messages, banners and the player's hurt go to the game
patch("E.msg=(t,dur)=>{E.toast={t,age:0,dur:dur||3};};", "E.msg=(t,dur)=>{HOST.msg(t,dur||3);};")
patch("let dmg=Math.max(Math.round(d*0.15),Math.round(d-PL_DEF));", "return HOST.hurt(d,o);let dmg=0;")
# our player moves itself (and our collision with it); the ground and the world still push and drag you
a = s.index("    const k=E.kb||{};let ux="); b = s.index("    // liquid that hurts")
s = s[:a] + "    const ground=tileAt(p.x,p.y);HOST.ground(p,ground,dt,mod);\n" + s[b:]
# our regeneration, not theirs
patch("    if(E.t-(p.lastHit||-9)>4&&p.hp<PL_HP&&!(p.noRegen>E.t))p.hp=Math.min(PL_HP,p.hp+14*dt);\n", "")
# our weapons, not the auto-fire (our shots reach their creatures through HOST: damageEnemy)
a = s.index("    // the player auto-fires at the nearest enemy it can see"); b = s.index("    if(!E.flowT||E.t-E.flowT>0.25)flowUpdate();")
s = s[:a] + s[b:]
# keys stay theirs (their locks count them); coins and potions are ours
patch("if(d.k==='coin')E.coins+=d.n||1;if(d.k==='potion')E.pots++;", "if(d.k==='coin'||d.k==='potion')HOST.pickup(d);")
patch("function drop(e){const d=e.d;", "function drop(e){const d=e.d;HOST.drop(e);if(0)")
# a chest's loot is ours (their boss drops are the uniques: they come from the boss)
patch("function openChest(pr){pr.used=1;pr.opened=1;", "function openChest(pr){pr.used=1;pr.opened=1;HOST.chest(pr);return;")
# the healing font heals you; a kill is ours to reward
patch("if(pr.k==='heal'&&d<1.3){p.hp=PL_HP;", "if(pr.k==='heal'&&d<1.3){HOST.heal();")
patch("function kill(e){e.hp=0;e.dead=0;E.kills++;", "function kill(e){e.hp=0;e.dead=0;E.kills++;HOST.kill(e);")
# our dungeons' feel (2026-10-19): no ring where a creature dies, no potions on the floor to walk over
patch("drop(e);pfx('boom',e.x,e.y,{r:e.d.size>16?2:0.8,c:'#ffffff'});", "drop(e);")
patch("if(Math.random()<0.05)E.drops.push({k:'potion',x:e.x+0.3,y:e.y});", "")   # (the 'if(0)' above guards only their coins)
patch("if(o.core&&Math.random()<0.3)E.drops.push({k:'potion',x:o.x+1.3,y:o.y+1});", "")
# a shrine's blessing is a buff on our player too
patch("if(pr.k==='shrine'&&d<1.1){pr.used=1;p.buff=60;", "if(pr.k==='shrine'&&d<1.1){pr.used=1;p.buff=60;HOST.shrine();")

# the Hall of Mirrors draws your reflection with the test player sprite, which stays out: no sprite, no reflection
patch("const im=E.player[Math.floor(p.f)%E.player.length];", "if(!E.player||!E.player.length)return;const im=E.player[Math.floor(p.f)%E.player.length];")
# strict mode (a module is strict, Realmforge's page was not): a loop that also tags the side names, which a page ignores
patch("for(const k in L){L[k].side='sun';Rr[k].side='moon';}", "for(const k in L){if(typeof L[k]==='object'){L[k].side='sun';Rr[k].side='moon';}}")

out = os.path.join(root, 'src', 'rf'); os.makedirs(out, exist_ok=True)
head = ("// Generated by tools/rf_build_explore.py from the user's Realmforge project (explore.js + xmods/*.js). Do not edit by\n"
        "// hand: change Realmforge and rebuild. The seams to our game are the HOST calls (src/rf/host.js).\n/* eslint-disable */\n")
open(os.path.join(out, 'explore_gen.js'), 'w', encoding='utf8', newline='\n').write(head + s)
print(f'src/rf/explore_gen.js: {len(s)} chars, {len(mods)} modules')
