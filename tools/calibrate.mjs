// Damage calibration: measures each monster's real damage per second against a level-20 character standing still
// 4 tiles away (the worst case: a sitting duck), and writes per-monster scale factors so every biome stays within
// its budget. Bosses aren't touched. Run after changing enemy attacks:  node tools/calibrate.mjs
import fs from 'node:fs';
import { Game } from '../src/game.js';
import { ENEMIES as E } from '../src/data/enemies.js';
globalThis.localStorage = { getItem: () => null, setItem: () => {} };
const BUDGET = { shore: 10, fen: 20, runeholt: 32, godfall: 50, forge: 50, chapel: 22, scriptorium: 38, heart: 55 };
const WHERE = { forge: 'godfall', chapel: 'fen', scriptorium: 'runeholt', heart: 'godfall' };     // dps taken while standing still, before your armour
const g = new Game({}, { fame: 0, gold: 0, essence: 0, vaults: [[], [], [], []], graveyard: [], chars: [], slots: 8, bestLevel: 0 });
const table = {};
for (const [id, D] of Object.entries(E)) {
  if (D.dummy || id === 'golden_duck' || id === 'coin_imp' || !BUDGET[D.biome]) continue;
  g.save.chars = []; g.newCharacter('priest'); g.command('/level 20'); g.command(`/tp ${WHERE[D.biome] || D.biome}`);
  const p = g.player, maxHp = g.stat('hp');
  g.enemies.length = 0; g.projectiles.length = 0;                     // alone with the monster under test
  g.maintainRealm = () => {}; g.eventClock = () => {}; g.updateQuirks = () => {};
  let taken = 0; const orig = g.hurtPlayer.bind(g);
  g.hurtPlayer = (d, by, ig) => { const h0 = p.hp; orig(d, by, ig); taken += Math.max(0, h0 - p.hp); p.hp = maxHp; };
  let sum = 0;
  for (let run = 0; run < 2; run++) {
    const e = g.addEnemy(id, p.x + 4, p.y + run); e.seen = true; if (e.D.children) e.kids = [];
    for (let i = 0; i < 12 * 60; i++) { g.update(1 / 60); p.hp = maxHp; if (e.dead) break; }
    e.dead = true; g.projectiles.length = 0;
  }
  sum = taken / 24;
  g.hurtPlayer = orig; g.leaveToMenu();
  const budget = BUDGET[D.biome] * (D.herald ? 2.2 : D.sheet === 'champions' ? 1.7 : D.elite ? 1.6 : 1);
  const f = sum > budget ? Math.max(0.12, budget / sum) : 1;
  table[id] = Math.round(f * 100) / 100;
  console.log(`${D.biome.padEnd(9)} ${id.padEnd(20)} ${sum.toFixed(0).padStart(4)} dps -> x${table[id]}`);
}
fs.writeFileSync(new URL('../src/data/tuning.js', import.meta.url),
  `// Generated by tools/calibrate.mjs: per-monster damage scale so each biome stays within its damage budget.\nexport const DMG_TUNE = ${JSON.stringify(table, null, 0).replace(/,/g, ', ')};\n`);
